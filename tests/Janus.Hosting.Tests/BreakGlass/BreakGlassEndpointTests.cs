    /// <summary>
    /// A deployment administered by one organization, whose reserved account holds the
    /// system administrator's permissions there, and whose owner has routine alerts
    /// turned off.
    /// </summary>
    public BreakGlassEndpointTests()
    {
        Flow.Prepare(_deployment);
        _deployment.Administers(Administration);

        _deployment.Configuration.Set(Settings.AlertingEmailDestinations, [Operator]);
        _deployment.Configuration.Set(Settings.AlertingSmsDestinations, [OperatorNumber]);
        _deployment.Configuration.Set(Settings.AlertingOwnerEmail, Owner);
        _deployment.Configuration.Set(Settings.AlertingOwnerSms, OwnerNumber);
        _deployment.Configuration.Set(Settings.AlertingOwnerEnabled, false);

        _emergency = SubjectId.New(_randomness);
        _deployment.Reserves(_emergency);
        _deployment.Accounts.Stands(_emergency, AccountState.Active);

        foreach (Permission permission in Permissions.All)
        {
            _deployment.Gate.Grant(_emergency, Administration, permission);
        }
    }

    /// <inheritdoc/>
    public async ValueTask DisposeAsync()
    {
        _randomness.Dispose();
        await _deployment.DisposeAsync();
    }

    /// <summary>
    /// OPS-BOOT-002 AC1: use opens a session for the reserved account and spends the
    /// credential, so the second attempt is refused as consumed, and a code that was
    /// never issued is refused as invalid.
    /// </summary>
    /// <returns>The work of the test.</returns>
    [Fact]
    public async Task OPS_BOOT_002_AC1_UseConsumesTheCredentialAsync()
    {
        string credential = await GeneratedAsync();

        Answer opened = await PresentedAsync(new Browser(_deployment), credential);
        Answer again = await PresentedAsync(new Browser(_deployment), credential);
        Answer unknown = await PresentedAsync(new Browser(_deployment), Drawn());

        Assert.Equal(StatusCodes.Status200OK, opened.Status);
        Assert.Contains(opened.SetCookie, cookie => cookie.StartsWith(BrowserCookies.Session + "=", StringComparison.Ordinal));
        Assert.Equal(_emergency, Assert.Single(_deployment.BreakGlassAudit.Used).Emergency);
        Assert.Equal(StatusCodes.Status409Conflict, again.Status);
        Assert.Equal(ErrorCodes.BreakGlassConsumed.ToString(), again.Text("code"));
        Assert.Equal(StatusCodes.Status422UnprocessableEntity, unknown.Status);
        Assert.Equal(ErrorCodes.BreakGlassInvalid.ToString(), unknown.Text("code"));
        Assert.NotNull(Assert.Single(_deployment.BreakGlass.Issues).ConsumedAt);
    }

    /// <summary>
    /// OPS-BOOT-002 AC2 and AUTH-STEP-004 AC3: the session ends at the configured
    /// lifetime however recently it was used, and the exception ends with it.
    /// </summary>
    /// <returns>The work of the test.</returns>
    [Fact]
    public async Task OPS_BOOT_002_AC2_TheSessionExpiresAtTheConfiguredLifetimeAsync()
    {
        _deployment.Configuration.Set(Settings.BreakGlassSessionLifetime, TimeSpan.FromHours(2));

        string credential = await GeneratedAsync();
        var owner = new Browser(_deployment);

        Assert.Equal(StatusCodes.Status200OK, (await PresentedAsync(owner, credential)).Status);

        Session opened = _deployment.Sessions.All.Single(session => session.Subject == _emergency);

        Assert.True(opened.SatisfiesEveryGate);
        Assert.Equal(_deployment.Clock.GetUtcNow().AddHours(2), opened.AbsoluteExpiry);

        _deployment.Clock.Advance(TimeSpan.FromMinutes(119));

        Answer live = await owner.SendAsync("GET", "/auth/session");

        _deployment.Clock.Advance(TimeSpan.FromMinutes(2));

        Answer ended = await owner.SendAsync("GET", "/auth/session");

        Assert.Equal(StatusCodes.Status200OK, live.Status);
        Assert.Equal(StatusCodes.Status401Unauthorized, ended.Status);
    }

