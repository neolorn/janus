    /// <summary>
    /// OPS-BOOT-004 AC3 and AC4: nothing reopens a code once answered, and a second
    /// generation answers a new one and invalidates the first; what is kept is a hash
    /// that holds neither.
    /// </summary>
    /// <returns>The work of the test.</returns>
    [Fact]
    public async Task OPS_BOOT_004_AC3_ASecondGenerationInvalidatesTheFirstAsync()
    {
        (Browser administrator, string first) = await AdministratorAsync();

        Answer second = await administrator.SendAsync("POST", Generate);
        string replacement = second.Text("credential");

        Assert.NotEqual(first, replacement);
        Assert.Equal(2, _deployment.BreakGlass.Issues.Count);
        Assert.NotNull(_deployment.BreakGlass.Issues[0].ReplacedAt);
        Assert.Equal(_deployment.BreakGlass.Issues[0].Id, _deployment.BreakGlassAudit.Generated[^1].Replaced);
        Assert.DoesNotContain(
            _deployment.BreakGlass.Issues,
            issue => issue.Hash.Encoded.Contains(first, StringComparison.Ordinal)
                || issue.Hash.Encoded.Contains(replacement, StringComparison.Ordinal));

        Answer stale = await PresentedAsync(new Browser(_deployment), first);
        Answer current = await PresentedAsync(new Browser(_deployment), replacement);

        Assert.Equal(StatusCodes.Status422UnprocessableEntity, stale.Status);
        Assert.Equal(ErrorCodes.BreakGlassInvalid.ToString(), stale.Text("code"));
        Assert.Equal(StatusCodes.Status200OK, current.Status);
    }

    /// <summary>
