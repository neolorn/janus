    /// <summary>
    /// OPS-BOOT-004: generation asks for system administration and a stepped-up
    /// session, so an administrator whose proof is no longer recent generates nothing.
    /// </summary>
    /// <returns>The work of the test.</returns>
    [Fact]
    public async Task OPS_BOOT_004_GenerationAsksForASteppedUpSystemAdministratorAsync()
    {
        Browser member = await Flow.SignedInAsync(_deployment);
        SubjectId subject = _deployment.Directory.Created[^1].Subject;

        Answer withheld = await member.SendAsync("POST", Generate);

        _deployment.Gate.Grant(subject, Administration, Permissions.SystemAdminister);
        _deployment.Clock.Advance(TimeSpan.FromDays(1));

        Answer challenged = await member.SendAsync("POST", Generate);

        Assert.Equal(StatusCodes.Status403Forbidden, withheld.Status);
        Assert.Equal(ErrorCodes.Denied.ToString(), withheld.Text("code"));
        Assert.Equal(StatusCodes.Status403Forbidden, challenged.Status);
        Assert.Equal(ErrorCodes.StepUpRequired.ToString(), challenged.Text("code"));
        Assert.Empty(_deployment.BreakGlass.Issues);
    }

