    // The deployment is one origin here, so what a browser would follow across two
    // applications is followed as a path of the one it is talking to.
    private static string Local(string? where)
    {
        const string origin = "https://identity.example.test";

        ArgumentNullException.ThrowIfNull(where);

        return where.StartsWith(origin, StringComparison.Ordinal) ? where[origin.Length..] : where;
    }

    // The instant a throttled answer says its interval lifts (API-CONV-003).
    private static DateTimeOffset Lifts(Answer answer) =>
        answer.Json().GetProperty("details").GetProperty("retryAt").GetDateTimeOffset();

    private static Task<Answer> ApprovedAsync(Browser browser, SubjectId subject) =>
        browser.SendAsync(
            "POST",
            "/admin/recovery/approve",
            ("subject", subject.ToString()),
            ("reason", "The administrator lost every factor."),
            ("channelUsed", Flow.Address));

    private static Task<Answer> PresentedAsync(Browser browser, string credential, IPAddress? source = null) =>
        browser.SendAsync(
            "POST",
            Present,
            JsonSerializer.Serialize(new { credential }),
            source: source);

    private string Drawn() => BreakGlassCode.Draw(_randomness);

    private AlertRaised Raised() =>
        _deployment.Events.Of<AlertRaised>().Last(raised => raised.Condition is AlertCondition.BreakGlassUsed);

    private async Task<string> GeneratedAsync() => (await AdministratorAsync()).Credential;

    // A stepped-up system administrator generating the first issue from the management
    // application.
    private async Task<(Browser Browser, string Credential)> AdministratorAsync()
    {
        Browser administrator = await Flow.SignedInAsync(_deployment);

        _deployment.Gate.Grant(_deployment.Directory.Created[^1].Subject, Administration, Permissions.SystemAdminister);

        Answer generated = await administrator.SendAsync("POST", Generate);

        Assert.Equal(StatusCodes.Status200OK, generated.Status);

        return (administrator, generated.Text("credential"));
    }
