    [Fact]
    public async Task OPS_BOOT_002_AC4_TheSessionGrantsSystemAdministrationAsync()
    {
        await _deployment.Roles.CreateAsync(Role.Of(SystemAdministrator, Permissions.All), CancellationToken.None);

        string credential = await GeneratedAsync();
        var owner = new Browser(_deployment);

        _ = await PresentedAsync(owner, credential);

        _deployment.Clock.Advance(TimeSpan.FromHours(1));

        Answer granted = await owner.SendAsync(
            "POST",
            "/admin/grants",
            ("subjectType", "user"),
